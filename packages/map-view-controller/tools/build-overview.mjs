// Precomputes the national overview outline.
//
// The India picker only ever draws each state's *district* rings, flattened to
// one silhouette per state. Deriving that in the browser meant importing all 36
// state modules first — ~9 MB raw / 2.4 MB gzipped — to throw away every
// sub-district path (the overwhelming bulk of it) and every ring vertex finer
// than a pixel at national zoom. This does that work once, here, and ships the
// result as a single small module.
//
//   node tools/build-overview.mjs [--tolerance <degrees>]
//
// Output: data/india-outline.js
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { STATES } from '../data/states/index.js';
import { parsePath } from '../src/state-map.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const flag = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`);
  return i === -1 ? fallback : process.argv[i + 1];
};

// Degrees of longitude/latitude. At national zoom India's ~30° span covers
// roughly 900 screen px, i.e. ~30 px per degree — so 0.02° is well under a
// pixel of error. Detail below this threshold is not merely unnoticeable, it is
// unrenderable. Pass --tolerance to trade size against fidelity.
const TOLERANCE = Number(flag('tolerance', 0.02));

/** Perpendicular distance from p to the segment ab. */
function segDistance(p, a, b) {
  let [x, y] = a;
  let dx = b[0] - x;
  let dy = b[1] - y;
  if (dx !== 0 || dy !== 0) {
    const t = ((p[0] - x) * dx + (p[1] - y) * dy) / (dx * dx + dy * dy);
    if (t > 1) [x, y] = b;
    else if (t > 0) { x += dx * t; y += dy * t; }
  }
  return Math.hypot(p[0] - x, p[1] - y);
}

/** Ramer–Douglas–Peucker, iterative so a 20k-point coastline can't blow the stack. */
function simplify(points, tolerance) {
  if (points.length < 3) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [first, last] = stack.pop();
    let index = -1;
    let maxDist = tolerance;
    for (let i = first + 1; i < last; i++) {
      const d = segDistance(points[i], points[first], points[last]);
      if (d > maxDist) { maxDist = d; index = i; }
    }
    if (index === -1) continue;
    keep[index] = 1;
    stack.push([first, index], [index, last]);
  }
  return points.filter((_, i) => keep[i]);
}

const round = (n) => Number(n.toFixed(4)); // ~11 m — far finer than this view resolves

let before = 0;
let after = 0;

const states = [];
for (const s of STATES) {
  const doc = (await import(`../data/states/${s.file}`)).default;
  const [vw] = doc.viewBox;
  const [minLon, minLat, maxLon, maxLat] = doc.bbox;
  const lat0 = (minLat + maxLat) / 2;
  const kx = Math.cos((lat0 * Math.PI) / 180);
  const scale = vw / ((maxLon - minLon) * kx);
  const toLonLat = ([x, y]) => [minLon + x / scale / kx, maxLat - y / scale];

  const districts = doc.districts.map((d) => {
    const rings = [];
    for (const ring of parsePath(d.path)) {
      before += ring.length;
      // A ring simplified below a triangle no longer encloses area; drop it
      // rather than hand ExtrudeGeometry a degenerate shape.
      const simplified = simplify(ring.map(toLonLat), TOLERANCE);
      if (simplified.length < 3) continue;
      after += simplified.length;
      rings.push(simplified.map(([lon, lat]) => [round(lon), round(lat)]));
    }
    return { rings };
  }).filter((d) => d.rings.length);

  states.push({ slug: s.slug, name: s.name, districts });
}

const out = `// Generated by tools/build-overview.mjs — do not edit.
//
// Every state's district rings in lon/lat, simplified to ${TOLERANCE}° — enough
// for the national picker and nothing more. Full-detail geometry lives in the
// per-state modules and is loaded only when a state is actually opened.
export default ${JSON.stringify(states)};
`;

const dest = resolve(ROOT, 'data/india-outline.js');
await writeFile(dest, out);
console.log(
  `india-outline.js — ${states.length} states, ` +
  `${before.toLocaleString()} → ${after.toLocaleString()} points ` +
  `(${(out.length / 1024).toFixed(0)} KB)`
);
